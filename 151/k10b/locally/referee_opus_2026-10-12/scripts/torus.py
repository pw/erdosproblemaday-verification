# Third source for the locally-C6 control: quotients of the triangular lattice by index-n sublattices (orientable),
# keep those whose graph is simple 6-regular with induced C6 links; compare with the search outputs; classify the
# search outputs by orientability of the triangle complex (H2(Z) = Z  <=> torus; else Klein bottle).
import itertools, networkx as nx, subprocess, sys
from sympy import Matrix
outs=[l.split()[1] for l in open(sys.argv[1]) if l.startswith("    ")]
NM=int(sys.argv[2])
C6=nx.cycle_graph(6)
tor=[]
for n in range(7,NM+1):
    for a in range(1,n+1):
        if n%a: continue
        d=n//a
        for b in range(d):
            # lattice L generated by (a,b),(0,d); quotient Z^2/L: reduce (x,y): y mod d ... use HNF reduction
            def red(x,y):
                q=x//a; x-=q*a; y-=q*b; y%=d; return (x,y)
            V=[(x,y) for x in range(a) for y in range(d)]
            G=nx.Graph(); G.add_nodes_from(V); bad=False
            for (x,y) in V:
                for dx,dy in [(1,0),(0,1),(1,-1)]:
                    w=red(x+dx,y+dy)
                    if w==(x,y): bad=True
                    G.add_edge((x,y),w)
            if bad or any(dd!=6 for _,dd in G.degree()): continue
            if all(nx.is_isomorphic(G.subgraph(G[v]),C6) for v in G):
                tor.append(nx.to_graph6_bytes(nx.convert_node_labels_to_integers(G),header=False).decode().strip())
canon=sorted(set(subprocess.run(["nauty-labelg","-q"],input="\n".join(tor)+"\n",capture_output=True,text=True).stdout.split()))
print("torus quotients (lattice construction), up to iso:", len(canon), "orders", [ord(c[0])-63 for c in canon])
print("all contained in the search output:", set(canon)<=set(outs))
ori=0; non=0
for s in outs:
    G=nx.from_graph6_bytes(s.encode()); E=sorted(tuple(sorted(e)) for e in G.edges()); eid={e:i for i,e in enumerate(E)}
    T=[tuple(sorted(c)) for c in nx.enumerate_all_cliques(G) if len(c)==3]
    D2=Matrix.zeros(len(E),len(T))
    for j,(p,q,r) in enumerate(T): D2[eid[(p,q)],j]=1; D2[eid[(q,r)],j]=1; D2[eid[(p,r)],j]=-1
    h2=len(T)-D2.rank()
    chi=G.number_of_nodes()-len(E)+len(T)
    if h2==1: ori+=1
    else: non+=1
    assert chi==0
print(f"search outputs: {len(outs)}; orientable (torus) {ori}; non-orientable (Klein bottle) {non}")
