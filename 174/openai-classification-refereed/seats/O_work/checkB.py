# Task (B): algebraic coordinates => F number field, B = F (x)_Q F = product of fields,
# m_F = projection onto ONE factor, P = e*(P0 (x) 1) satisfies (1),(2).
# Concrete: F = Q(alpha), alpha = 2^(1/3) (non-Galois). B = Q[x,y]/(x^3-2, y^3-2), x=alpha(x)1, y=1(x)alpha.
import sympy as sp
x, y, a = sp.symbols('x y a')
G = sp.groebner([x**3 - 2, y**3 - 2], x, y, order='lex', domain='QQ')
red = lambda f: G.reduce(sp.expand(f))[1]
mF = lambda f: sp.nsimplify(sp.expand(f.subs({x: sp.cbrt(2), y: sp.cbrt(2)})))   # x(x)y -> product

# factorisation of y^3-2 over F=Q(x): (y-x)(y^2+xy+x^2); the second factor is irreducible over Q(2^(1/3))
# (its roots are x*omega, omega a primitive cube root of 1, not real) -> B = F x Q(2^(1/3),omega): two factors.
print('y^3-2 over Q(2^(1/3)):', sp.factor(y**3 - 2, extension=sp.cbrt(2)))
e = red((x*y**2 + x**2*y + 2) / 6)     # = g(y)/g(x) with g(y)=(y^3-2)/(y-x)=y^2+xy+x^2, 1/(3x^2) = x/6
print('e                         =', e)
print('e^2 - e  (mod ideal)      =', red(e**2 - e))
print('(x - y) e (mod ideal)     =', red((x - y)*e))
print('m_F(e)                    =', mF(e))
# kernel of m_F is generated by x-y; e kills it, so e*b depends only on m_F(b): e*b = e*(m_F(b)(x)1)
# check: for random b, e*b - e*(m_F(b) lifted as polynomial in x) == 0
import random; random.seed(1)
for _ in range(5):
    b = sum(random.randint(-5, 5)*x**i*y**j for i in range(3) for j in range(3))
    mb = sp.expand(b.subs(y, x))          # m_F(b) written as element of F in the 'x' copy
    assert red(e*b - e*mb) == 0
print('e*b = e*(m_F(b) (x) 1) for random b: OK  =>  e*b = 0 iff m_F(b) = 0')

# A spherical set with coordinates in F: centre (alpha,0), radius alpha, 7 points alpha*(1+u_j, v_j),
# (u_j,v_j) rational points of the unit circle.  Seven circle points: Prop 7.3 does NOT apply (rank<=6).
pyth = [(1, 0), (0, 1), (-1, 0), (sp.Rational(3, 5), sp.Rational(4, 5)), (sp.Rational(-5, 13), sp.Rational(12, 13)),
        (sp.Rational(8, 17), sp.Rational(-15, 17)), (sp.Rational(-7, 25), sp.Rational(-24, 25))]
def pts(al): return [sp.Matrix([1, al*(1 + u), al*v]) for (u, v) in pyth]
# sphere matrix over F: p^T P0 p = |a|^2 - 2 z.a - kappa, z = (alpha,0), kappa = rho^2 - |z|^2 = 0
P0 = lambda al: sp.Matrix([[0, -al, 0], [-al, 1, 0], [0, 0, 1]])
Px = P0(x)                               # entries lifted as c (x) 1  (c in the x-copy)
P = (e*Px).applyfunc(red)                # P = e * (P0 (x) 1)
vals = []
for px, py in zip(pts(x), pts(y)):       # (p_i (x) 1) and (1 (x) p_i)
    vals.append(red((px.T*P*py)[0]))
print('(1): (p_i(x)1)^T P (1(x)p_i) for the 7 points:', vals)
print('(2): m_F(P_ab) spatial block:', [[mF(P[i, j]) for j in (1, 2)] for i in (1, 2)])
# Prop 7.3 hypothesis fails: 7 quadratic rows in F^9 have rank <= 6
al = sp.cbrt(2)
rows = sp.Matrix([[p[i]*p[j] for i in range(3) for j in range(3)] for p in pts(al)])
print('rank of the 7 quadratic rows (Prop 7.3 needs 7):', rows.rank(simplify=True))
# without e the naive lift P0(x)1 fails (1): tensor evaluations nonzero
naive = [red((px.T*Px*py)[0]) for px, py in zip(pts(x), pts(y))]
print('control: naive P0(x)1 evaluations (should be nonzero):', naive[:3])
