"""Referee checks for section C of CLAIMS.md (ENS 1988 route).
(e) table: min over s >= 1 of  (k+s) + floor(k + (k^2-2k)/s) - 1  vs 4k-4, k = 2..60.
    Also the ratio of the upper bound 4*ceil(1/d)-4 to the lower bound floor(2/d)-1 over a fine delta grid.
(f) exhaustive periodic sets A = {n >= 1 : n mod m in S}, S subset of Z/m, m <= MMAX, that satisfy the residue
    hypothesis; true restricted order computed by exact distinct-summand DP (big-int bitsets) on [1, N]
    (order := least t with no exception to '<= t distinct' in [N/2, N]); compared with 4*ceil(m/|S|) - 4
    (Theorem C, for density <= 1/2) and with 3*ceil(2m/|S|) - 2 (A'').
    Plus a few non-periodic structured sets.
"""
from math import gcd, ceil, floor
from fractions import Fraction as F
from itertools import combinations
import random, sys

# (e)
print("(e) k, 4k-4, best over s of (k+s)+floor(k+(k^2-2k)/s)-1, argmin s")
better = []
for k in range(2, 61):
    best = None
    for s in range(1, 4 * k * k):
        G = k + F(k * k - 2 * k, s)
        g = max(1, floor(G))
        tot = (k + s) + g - 1
        if best is None or tot < best[0]: best = (tot, [s])
        elif tot == best[0]: best[1].append(s)
    if best[0] < 4 * k - 4: better.append((k, best[0], best[1][:4]))
    if k <= 12 or k % 10 == 0:
        print(f"   k={k:2d}  4k-4={4*k-4:4d}  best={best[0]:4d}  s in {best[1][:6]}")
print("   k in 2..60 where some s beats 4k-4:", better if better else "none")

# ratio upper/lower over delta grid
worst = (0, None)
for q in range(2001, 200001, 7):
    d = F(1000, q)            # delta from ~1/2 down to 1/200
    if d > F(1, 2): continue
    up = 4 * ceil(1 / d) - 4
    lo = floor(2 / d) - 1
    r = F(up, lo)
    if r > worst[0]: worst = (r, d)
print(f"   max over delta in [1/200,1/2] of (4ceil(1/d)-4)/(floor(2/d)-1) = {float(worst[0]):.3f} at delta={float(worst[1]):.4f}")
for d in (F(1, 2), F(1, 5), F(1, 10), F(1, 50), F(49, 100), F(1, 3) + F(1, 1000)):
    print(f"   delta={str(d):>8s}: Theorem C {4*ceil(1/d)-4}, A'' {3*ceil(2/d)-2}, example lower {floor(2/d)-1}")

# (f)
def gen_ok(S, m, gmax):
    """residue hypothesis for the periodic set: for every g <= gmax the classes mod g hit infinitely often
    (= {s + gcd(m,g)Z}) generate Z/g."""
    for g in range(2, gmax + 1):
        d = gcd(m, g)
        cls = set()
        for s in S:
            for j in range(g // d):
                cls.add((s + d * j) % g)
        # subgroup generated by cls in Z/g = gcd(g, all elements) Z
        h = g
        for c in cls: h = gcd(h, c)
        if h != 1: return False
    return True

def restricted_order(Aelems, N, tmax):
    """least t <= tmax with no n in [N//2, N] outside 'sum of <= t distinct elements', else None.
    layers[j] = bitset of sums of exactly j distinct elements (<= N)."""
    mask = (1 << (N + 1)) - 1
    layers = [1] + [0] * tmax
    for e in Aelems:
        for j in range(tmax, 0, -1):
            layers[j] |= (layers[j - 1] << e) & mask
    cover = 0
    upper = ((1 << (N + 1)) - 1) ^ ((1 << (N // 2)) - 1)
    for t in range(1, tmax + 1):
        cover |= layers[t]
        if (cover & upper) == upper: return t
    return None

MMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 10
viol = []; rows = 0; maxratio = (0, None); tight = []
for m in range(2, MMAX + 1):
    for r in range(1, m):
        for S in combinations(range(m), r):
            if F(r, m) > F(1, 2): continue
            if not gen_ok(S, m, 4 * m): continue
            k = ceil(F(m, r))
            boundC = 4 * k - 4
            N = max(40 * m * m, 600)
            A = [n for n in range(1, N + 1) if n % m in S]
            t = restricted_order(A, N, boundC + 2)
            rows += 1
            if t is None or t > boundC: viol.append((m, S, t, boundC))
            else:
                if F(t, boundC) > maxratio[0]: maxratio = (F(t, boundC), (m, S, t, boundC))
                lo = floor(F(2 * m, r)) - 1
                if t > lo: tight.append((m, S, t, lo, boundC))
print(f"(f) periodic sets m<={MMAX}, density<=1/2, residue hypothesis: {rows} sets; violations of 4ceil(1/d)-4: "
      f"{viol if viol else 'none'}")
print(f"    max true/boundC = {maxratio[0]} at (m,S,t,boundC) = {maxratio[1]}")
print(f"    sets whose true order exceeds floor(2/d)-1 (the example's value): {len(tight)}; first {tight[:8]}")

# non-periodic structured sets
rnd = random.Random(5)
extra = []
N = 6000
for m in (3, 4, 5, 6):
    # multiples of m plus a sparse (lacunary) set of elements = 1 mod m
    A = sorted(set([n for n in range(m, N + 1, m)] + [m * (2 ** j) + 1 for j in range(1, 20) if m * 2 ** j + 1 <= N]))
    extra.append((f"mN u {{m2^j+1}}, m={m}", A, F(1, m)))
    # {0,1 mod m} with every 3rd element of class 1 removed (density 1/m + 2/(3m))
    A = [n for n in range(1, N + 1) if n % m == 0 or (n % m == 1 and (n // m) % 3 != 0)]
    extra.append((f"0 mod m u 2/3 of 1 mod m, m={m}", A, F(5, 3 * m)))
for name, A, d in extra:
    k = ceil(1 / d); boundC = 4 * k - 4
    t = restricted_order(A, N, boundC + 2)
    print(f"    {name:34s} density {str(d):>5s}: true order (window) {t}, Theorem C bound {boundC}"
          + ("   <-- VIOLATION" if t is None or t > boundC else ""))
