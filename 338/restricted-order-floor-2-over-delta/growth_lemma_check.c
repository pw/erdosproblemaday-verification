/* Exhaustive check of the growth lemma used in the 2/delta bound (Erdos #338 follow-up a).
   Lemma: in Z/g, if 0 in S, S generates Z/g, and Z+S != Z/g, then |Z+S| >= |Z| + ceil(|S|/2).
   Checks every nonempty Z and every generating S containing 0, for g <= GMAX.
   Also reports, as a NEGATIVE CONTROL, the count of violations when the generation hypothesis is dropped
   (it must be > 0, or the checker could only say pass), and the sharper claim |Z+S| >= |Z|+|S|-1
   (false in general because of stabilisers; it must FAIL somewhere for composite g). */
#include <stdio.h>
#include <stdlib.h>
typedef unsigned int u32;
static int g;
static u32 rot(u32 x,int k){ u32 m=(1u<<g)-1; k%=g; return ((x<<k)|(x>>(g-k)))&m; }
static u32 sumset(u32 Z,u32 S){ u32 r=0; for(int k=0;k<g;k++) if(S>>k&1) r|=rot(Z,k); return r; }
static int gen(u32 S){ /* subgroup generated by S = closure under + */
  u32 cl=1; for(int it=0;it<g;it++){ u32 n=cl|sumset(cl,S); if(n==cl) break; cl=n;} return cl==((1u<<g)-1); }
int main(int argc,char**argv){
  int GMAX=argc>1?atoi(argv[1]):12;
  for(g=1;g<=GMAX;g++){
    u32 full=(1u<<g)-1; long long checked=0,viol=0,ctrl_viol=0,sharp_viol=0;
    for(u32 S=1;S<=full;S+=2){ /* bit0 set: 0 in S */
      int s=__builtin_popcount(S); int G=gen(S);
      for(u32 Z=1;Z<=full;Z++){
        u32 ZS=sumset(Z,S); if(ZS==full) continue;
        int dz=__builtin_popcount(ZS)-__builtin_popcount(Z);
        if(G){ checked++; if(dz < (s+1)/2) viol++; if(dz < s-1) sharp_viol++; }
        else { if(dz < (s+1)/2) ctrl_viol++; }
      }
    }
    printf("g=%2d checked=%lld violations=%lld | control(non-generating S) violations=%lld | sharp(|S|-1) violations=%lld\n",
           g,checked,viol,ctrl_viol,sharp_viol);
  }
  return 0;
}
