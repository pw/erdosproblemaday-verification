#!/usr/bin/env python3
"""Erdős #203 — the LINE LEMMA as an exact finite test.

Setup (as in the shipped entry): prime p ≥ 5, H_p = <2,3> ≤ (Z/p)^×, e_p = |H_p|, L_p = {(k,l): u k + v l ≡ 0 (mod e_p)}
(2 ↦ u, 3 ↦ v under Z^2 → Z/e_p ≅ H_p).  A #203 covering is a choice of ONE coset C_p of L_p per prime of a finite set P
with ∪ C_p = Z^2.

Line lemma.  Fix a primitive direction d = (a,b) and let g = 2^a 3^b ↦ a u + b v =: s_p (mod e_p).  The lines
{x + t·d : t ∈ Z} are indexed by their transverse class τ ∈ Z (τ = b k − a l).  Along a line, 2^k 3^l runs through a coset
of <g>, so C_p meets a line in either nothing or ONE residue class modulo ord_p(g) = e_p / gcd(s_p, e_p); and the lines
it meets form ONE residue class of τ modulo i_p := gcd(s_p, e_p) = [H_p : <g>]  (because H_p/<g> is cyclic, generated by
the image of the transverse generator).  So on the lines it meets, C_p has 1-dimensional density  w_p := i_p / e_p
= 1/ord_p(g), and on all other lines density 0.  Averaged over τ this is 1/e_p, as it must be.
Consequence: if ∪ C_p = Z^2 then for EVERY τ,   W(τ) := Σ_{p : τ ≡ t_p (mod i_p)} w_p  ≥ 1,
where t_p ∈ Z/i_p is the line class of C_p (determined by m; every value occurs for some m, independently over p).

Coarsening.  For any modulus M' the average of W over a progression τ ≡ c (mod M') is Σ_p [c ≡ t_p (mod gcd(i_p,M'))]·
gcd(i_p,M')/e_p — the same shape with i_p ↦ gcd(i_p, M').  Since min ≤ average, the coarse condition is NECESSARY too,
and it is exact when lcm(i_p) | M'.

What this script computes:  V(P, d, M') := max over all t of min over τ of W(τ)  — an exact rational.  V < 1 ⇒ no
#203 covering uses exactly the primes P (and, since W only grows with P, none uses a SUBSET of P — the pool test).
Instruments: OR-tools CP-SAT (max z), exhaustive brute force when ∏ i_p is small, HiGHS MILP (scipy) as a third;
every witness t returned by a solver is re-counted exactly in Fractions by an independent loop.
Controls (--control): the classical 1-D covering 0(2),0(3),1(4),3(8),7(12),23(24) as a pool of full-weight classes
must give V ≥ 1 (feasible); the moduli {2,3,4,8} cannot cover Z (max union 22/24 — a different quantity), so some line is bare and V = 0; must be rejected.
"""
import json, sys, argparse, itertools, time
from math import gcd
from fractions import Fraction as F
from functools import reduce

def lcm(a,b): return a*b//gcd(a,b)

def instance(pool, d, Mp=None):
    """Return E (Fraction), lumpy list [(p, i, w Fraction)], M'' = lcm of lumpy i, and the everywhere list."""
    a,b = d
    E = F(0); lum=[]; ev=[]
    for q in pool:
        e,u,v = q['e'], q['u'], q['v']
        s = (a*u + b*v) % e
        i = gcd(s, e) if s else e
        if Mp is not None: i = gcd(i, Mp)
        w = F(i, e)
        if i == 1: E += w; ev.append((q['p'], w))
        else: lum.append((q['p'], i, w))
    M = reduce(lcm, [i for _,i,_ in lum], 1)
    return E, lum, M, ev

PRIME_ZETA_2 = 0.45224742004106549850654336483224793417323134323989  # Σ_{p prime} 1/p² (P(2)); rounded UP below
def pp_extras(d, Mp):
    """Perfect-power variant (Theorem C's free sets, credited WITHOUT their residue price — more generous to the adversary).
    F_q = qZ^2 for odd primes q: π(qZ^2) = qZ (d primitive), on those lines density 1/q ⇒ a lump (i=q, w=1/q, e=q^2) at the
    FIXED class 0. Coarsened to M: i' = gcd(q,M), w' = i'/q^2 — so for q ∤ M the lump IS the uniform 1/q^2 (the coarsening
    lemma), and we keep exact lumps only for the odd primes q | M; every other odd prime contributes the uniform 1/q^2,
    summed in closed form as P(2) − 1/4 − Σ_{q|M} 1/q^2 and rounded UP. The Aurifeuillean set (2,0)+4Z^2: lines
    τ ≡ π(2,0) = 2b (mod 4), density 1/4 ⇒ lump (i=gcd(4,M), w=i/16, class 2b) — uniform 1/16 if 4 ∤ M.
    Returns (fixed lumps [(i,w,class)], uniform tail as a float to be rounded up at the caller's scale)."""
    from sympy import factorint
    a,b = d
    fixed = []; tail = PRIME_ZETA_2 - 0.25
    for q in factorint(Mp):
        if q == 2: continue
        fixed.append((q, F(1, q), 0)); tail -= 1.0/(q*q)
    i4 = gcd(4, Mp)
    if i4 == 1: tail += 1.0/16
    else: fixed.append((i4, F(i4, 16), (2*b) % i4))
    return fixed, tail

def recount(E, lum, M, t):
    """Exact Fraction recount of min_τ W(τ) for the line classes t (list aligned with lum). Independent of any solver."""
    best = None
    for tau in range(M):
        W = E
        for (p,i,w),tp in zip(lum, t):
            if tau % i == tp: W += w
        if best is None or W < best: best = W
    return best

def recount_np(E, lum, M, t):
    import numpy as np
    S = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator], 1)
    W = np.full(M, int(E*S), dtype=np.int64)
    tau = np.arange(M)
    for (p,i,w),tp in zip(lum, t):
        W[tau % i == tp] += int(w*S)
    return F(int(W.min()), S)

def brute(E, lum, M, limit=3_000_000):
    """Exhaustive max over t of min_τ W(τ). Returns (V, t) or None if too big."""
    import numpy as np
    cfg = 1
    for _,i,_ in lum: cfg *= i
    if cfg > limit or M > 200000: return None
    S = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator], 1)
    tau = np.arange(M)
    masks = [[(tau % i == r) for r in range(i)] for _,i,_ in lum]
    wint = [int(w*S) for _,_,w in lum]
    base = np.full(M, int(E*S), dtype=np.int64)
    best=-1; bt=None
    for t in itertools.product(*[range(i) for _,i,_ in lum]):
        W = base.copy()
        for j,tp in enumerate(t): W[masks[j][tp]] += wint[j]
        m = int(W.min())
        if m > best: best, bt = m, t
    return F(best, S), list(bt)

def cpsat(E, lum, M, time_limit=600, workers=4, fix_one=True, fixed=(), feas=False):
    from ortools.sat.python import cp_model
    S = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator], 1)
    m = cp_model.CpModel()
    x = []
    for j,(p,i,w) in enumerate(lum):
        xs = [m.NewBoolVar(f"x{j}_{r}") for r in range(i)]
        m.AddExactlyOne(xs); x.append(xs)
    for (i,w,cls) in fixed:   # fixed-class lumps (free sets): forced variables
        xs = [m.NewBoolVar(f"f{i}_{r}") for r in range(i)]
        m.AddExactlyOne(xs); m.Add(xs[cls % i] == 1); x.append(xs)
    if fixed: fix_one = False   # a fixed class breaks the translation symmetry
    if fix_one and lum:
        # translation symmetry: shifting every t_p by the same c permutes τ; fix the first lumpy prime's class to 0
        m.Add(x[0][0] == 1)
    S = reduce(lcm, [S] + [w.denominator for _,w,_ in fixed], 1)
    Eint = int(E*S); wint = [int(w*S) for _,_,w in lum] + [int(w*S) for _,w,_ in fixed]
    idx = [i for _,i,_ in lum] + [i for i,_,_ in fixed]
    ub = Eint + sum(wint)
    z = m.NewIntVar(S if feas else 0, ub, "z")
    for tau in range(M):
        m.Add(sum(wint[j]*x[j][tau % idx[j]] for j in range(len(idx))) + Eint >= z)
    if not feas: m.Maximize(z)
    s = cp_model.CpSolver(); s.parameters.max_time_in_seconds = time_limit; s.parameters.num_workers = workers
    st = s.Solve(m)
    name = s.StatusName(st)
    if feas:
        if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
            t = [next(r for r in range(lum[j][1]) if s.Value(x[j][r])) for j in range(len(lum))]
            return name, F(int(s.Value(z)), S), None, t, s.WallTime()
        return name, None, None, None, s.WallTime()
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        t = [next(r for r in range(lum[j][1]) if s.Value(x[j][r])) for j in range(len(lum))]
        ov, bv = s.ObjectiveValue(), s.BestObjectiveBound()
        assert abs(ov - round(ov)) < 1e-6 and abs(bv - round(bv)) < 1e-6, (ov, bv)
        return name, F(int(round(ov)), S), F(int(round(bv)), S), t, s.WallTime()
    return name, None, None, None, s.WallTime()

def recount_fixed(E, lum, M, t, fixed):
    import numpy as np
    S = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator] + [w.denominator for _,w,_ in fixed], 1)
    W = np.full(M, int(E*S), dtype=np.int64); tau = np.arange(M)
    for (p,i,w),tp in zip(lum, t): W[tau % i == tp] += int(w*S)
    for (i,w,cls) in fixed: W[tau % i == (cls % i)] += int(w*S)
    return F(int(W.min()), S)

def milp(E, lum, M, time_limit=600, feas=False):
    """scipy HiGHS MILP, same formulation; decorrelated from CP-SAT."""
    import numpy as np
    from scipy.optimize import milp, LinearConstraint, Bounds
    from scipy.sparse import lil_matrix
    S = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator], 1)
    nv = sum(i for _,i,_ in lum) + 1  # + z
    off=[0]
    for _,i,_ in lum: off.append(off[-1]+i)
    zi = off[-1]
    A = lil_matrix((M + len(lum), nv))
    lo = np.zeros(M+len(lum)); hi = np.full(M+len(lum), np.inf)
    Eint = int(E*S); wint=[int(w*S) for _,_,w in lum]
    for tau in range(M):
        for j,(p,i,w) in enumerate(lum): A[tau, off[j] + tau % i] = wint[j]
        A[tau, zi] = -1; lo[tau] = -Eint
    for j,(p,i,w) in enumerate(lum):
        for r in range(i): A[M+j, off[j]+r] = 1
        lo[M+j] = 1; hi[M+j] = 1
    c = np.zeros(nv); c[zi] = -1
    integ = np.ones(nv);
    lb = np.zeros(nv); 
    if feas: lb[zi] = S
    b = Bounds(lb, np.concatenate([np.ones(nv-1),[Eint+sum(wint)]]))
    res = milp(c, constraints=LinearConstraint(A.tocsr(), lo, hi), integrality=integ, bounds=b, options={"time_limit": time_limit})
    db = getattr(res, "mip_dual_bound", None)
    dbF = F(int(round(-db)), S) if db is not None else None   # maximisation written as min of −z: bound on max z = −dual_bound
    if res.x is None: return res.status, None, None, dbF
    t = [int(np.argmax(res.x[off[j]:off[j+1]])) for j in range(len(lum))]
    return res.status, F(int(round(-res.fun)), S), t, dbF

def run(pool, d, Mp, args, label=""):
    E, lum, M, ev = instance(pool, d, Mp)
    fixed = ()
    if getattr(args, 'pp', 0):
        import math
        fixed, tail = pp_extras(d, Mp if Mp else M)
        S0 = reduce(lcm, [w.denominator for _,_,w in lum] + [E.denominator] + [w.denominator for _,w,_ in fixed], 1)
        const = F(math.ceil(tail*S0) + 1, S0)   # rounded up, one extra unit: the safe direction
        E = E + const
        M = reduce(lcm, [M] + [i for i,_,_ in fixed], 1)
    Lam = sum(F(1, w.denominator) * 1 for _,_,w in lum)  # not used; density below
    dens = E + sum(w/i for _,i,w in lum)
    if fixed: dens = dens + sum(w/i for i,w,_ in fixed)
    out = {"label": label, "dir": d, "Mp": Mp, "E": str(E), "E_f": float(E), "density": str(dens), "density_f": float(dens),
           "lumpy": len(lum), "M": M, "prod_i": 1, "pp": getattr(args,'pp',0), "fixed_lumps": [(i,str(w),c) for i,w,c in fixed]}
    for _,i,_ in lum: out["prod_i"] *= i
    t0=time.time()
    if getattr(args, 'feas', False):
        name, V, bound, t, wt = cpsat(E, lum, M, args.time, args.workers, fixed=fixed, feas=True)
        out["feas"] = {"cpsat_status": name, "wall": wt, "t": t}
        if t is not None:
            rc = recount_fixed(E, lum, M, t, fixed) if fixed else recount_np(E, lum, M, t)
            out["feas"]["recount"] = str(rc); out["feas"]["recount_ok"] = (rc >= 1)
        if args.milp:
            try:
                stt, Vm, tm, dbm = milp(E, lum, M, getattr(args,'milp_time',None) or args.time, feas=True)
                out["feas"]["milp_status"] = int(stt); out["feas"]["milp_t"] = tm
                if tm is not None:
                    rcm = recount_np(E, lum, M, tm); out["feas"]["milp_recount"] = str(rcm); out["feas"]["milp_recount_ok"] = (rcm >= 1)
            except Exception as ex: out["feas"]["milp_error"] = repr(ex)
        cp_inf = (name == "INFEASIBLE"); mi_inf = (out["feas"].get("milp_status") == 2)
        out["verdict"] = ("EXCLUDED (CP-SAT INFEASIBLE)" if cp_inf else "") + (" + HiGHS INFEASIBLE" if mi_inf else "") or \
                         ("not excluded (witness re-counted ≥ 1)" if t is not None else "UNDECIDED (time limit)")
        out["excluded"] = cp_inf or mi_inf
        print(json.dumps(out), flush=True); return out
    name, V, bound, t, wt = cpsat(E, lum, M, args.time, args.workers, fixed=fixed)
    out["cpsat"] = {"status": name, "V": str(V) if V is not None else None, "V_f": float(V) if V is not None else None,
                    "bound": str(bound) if bound is not None else None, "t": t, "wall": wt}
    if t is not None:
        rc = recount_fixed(E, lum, M, t, fixed) if fixed else recount_np(E, lum, M, t); out["cpsat"]["recount"] = str(rc)
        # z is a free variable bounded above by every W(τ); at OPTIMAL it equals the min, on a time-limited solution it may sit below it
        out["cpsat"]["recount_ok"] = (rc == V) if name == "OPTIMAL" else (rc >= V)
        if not out["cpsat"]["recount_ok"]: print("!! RECOUNT BELOW REPORTED VALUE", label, d, rc, V, file=sys.stderr)
    if fixed: args.brute = False; args.milp = False   # second instruments not wired for fixed lumps (pp mode is a corollary run)
    if args.brute:
        br = brute(E, lum, M, args.brute_limit)
        if br is not None:
            Vb, tb = br; rcb = recount(E, lum, M, tb)
            out["brute"] = {"V": str(Vb), "t": tb, "recount": str(rcb), "agrees_cpsat": (V == Vb)}
            if V != Vb: print("!! BRUTE/CPSAT DISAGREE", label, d, Vb, V, file=sys.stderr)
    if args.milp:
        try:
            stt, Vm, tm, dbm = milp(E, lum, M, getattr(args, 'milp_time', None) or args.time)
            out["milp"] = {"status": int(stt), "V": str(Vm) if Vm is not None else None, "t": tm, "bound": str(dbm) if dbm is not None else None,
                           "recount": str(recount_np(E, lum, M, tm)) if tm is not None else None, "agrees_cpsat": (Vm == V),
                           "excludes": (dbm is not None and dbm < 1)}
            if Vm is not None and V is not None and Vm != V: print("!! MILP/CPSAT DISAGREE", label, d, Vm, V, file=sys.stderr)
        except Exception as ex:
            out["milp"] = {"error": repr(ex)}
    verdict = None
    if V is not None and name == "OPTIMAL":
        verdict = "EXCLUDED" if V < 1 else "not excluded (witness t found, re-counted)"
    elif V is not None:
        if V >= 1: verdict = "not excluded (feasible t found)"
        elif bound < 1: verdict = f"EXCLUDED by bound (proven max ≤ {float(bound):.4f} < 1; best found {float(V):.4f})"
        else: verdict = f"UNDECIDED (best {float(V):.4f} < 1 but bound {float(bound):.4f})"
    elif name in ("INFEASIBLE",): verdict = "EXCLUDED (model infeasible — should not happen with z free)"
    out["verdict"] = verdict; out["excluded"] = verdict is not None and verdict.startswith("EXCLUDED")
    print(json.dumps(out), flush=True)
    return out

def controls(args):
    # classical covering of Z: 0(2) 0(3) 1(4) 3(8) 7(12) 23(24); full-weight classes ⇔ e = i, w = 1
    pos = [{"p":"c%d"%i, "e":i, "u":1, "v":0} for i in (2,3,4,8,12,24)]
    neg = [{"p":"c%d"%i, "e":i, "u":1, "v":0} for i in (2,3,4,8)]
    # direction (0,1): s = v = 0 ⇒ i = e, w = 1 (whole residue classes of τ)
    class A: pass
    a = A(); a.time=args.time; a.workers=args.workers; a.brute=True; a.brute_limit=10**6; a.milp=True
    print("# CONTROL positive (must be ≥ 1):"); r1 = run(pos, (0,1), None, a, "control_pos_{2,3,4,8,12,24}")
    print("# CONTROL negative (an uncovered point exists ⇒ V must be exactly 0):"); r2 = run(neg, (0,1), None, a, "control_neg_{2,3,4,8}")
    ok = (F(r1["cpsat"]["V"]) >= 1) and (F(r2["cpsat"]["V"]) == 0) and r1["brute"]["agrees_cpsat"] and r2["brute"]["agrees_cpsat"] and r1["milp"]["agrees_cpsat"] and r2["milp"]["agrees_cpsat"]
    # mutation: shift E by +1/7 on the negative control ⇒ V must shift by exactly 1/7
    E, lum, M, ev = instance(neg, (0,1), None)
    name, V, bound, t, wt = cpsat(E + F(1,7), lum, M, args.time, args.workers)
    ok = ok and (V == F(0) + F(1,7))
    print("# CONTROL E-shift (V must move by exactly the shift):", V, "expected", F(1,7))
    # exact 2-D partition: the 4 cosets of L_5 and the 6 cosets of L_7 as ten 'primes' — in every direction the lumpy
    # structure (1 < i < e, fractional weights) must still let the adversary reach V = exactly 1 (choose the cosets distinct)
    part5 = [{"p":f"5c{c}","e":4,"u":3,"v":1} for c in range(4)]; part7 = [{"p":f"7c{c}","e":6,"u":2,"v":1} for c in range(6)]
    dirs=[(1,0),(0,1),(1,1),(1,-1),(2,1),(1,2),(2,-1),(1,-2),(3,1),(1,3),(3,-1),(1,-3),(3,2),(2,3),(3,-2),(2,-3),(5,-7)]
    for dd in dirs:   # one complete partition ⇒ the adversary can reach exactly 1 (cosets distinct) and never more
        E, lum, M, ev = instance(part5, dd, None); name, V, bound, t, wt = cpsat(E, lum, M, args.time, args.workers, fix_one=False)
        if V != 1 or name != "OPTIMAL": print("# CONTROL partition FAIL", dd, name, V); ok = False
        E, lum, M, ev = instance(part5+part7, dd, None); name, V, bound, t, wt = cpsat(E, lum, M, args.time, args.workers, fix_one=False)
        if V != 2 or name != "OPTIMAL": print("# CONTROL double partition FAIL", dd, name, V); ok = False
    print("# CONTROL exact partitions (the 4 cosets of L_5 ⇒ V = 1; plus the 6 cosets of L_7 ⇒ V = 2) in all", len(dirs), "directions")
    # mutation: drop one coset of L_7; in direction (0,1) (g = 3, ord_7 3 = 6, i = 1) each L_7 coset is an everywhere-prime of
    # weight 1/6 ⇒ V = 2 − 1/6 exactly
    E, lum, M, ev = instance(part5+part7[:-1], (0,1), None); name, V, bound, t, wt = cpsat(E, lum, M, args.time, args.workers, fix_one=False)
    print("# CONTROL mutation (drop one L_7 coset, direction (0,1)):", V, "expected 11/6"); ok = ok and V == F(11,6)
    print("CONTROLS", "PASS" if ok else "FAIL")
    return 0 if ok else 2

