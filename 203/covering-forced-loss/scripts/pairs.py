#!/usr/bin/env python3
"""#203 pairwise structure for a pool: for primes p,q the cosets C_p, C_q (chosen arbitrarily) intersect, when they
meet, in a coset of L_p ∩ L_q, whose index is e_{pq} := |<2,3> in (Z/pq)^*| = |image of Z^2 in Z/e_p x Z/e_q|.
They meet for EVERY choice iff e_{pq} = e_p e_q (L_p + L_q = Z^2).  Forced pairwise overlap = 1/e_{pq} in that case.
Route 1 (group-theoretic): e_{pq} = ord(g1) ord(g2) / |<g1> ∩ <g2>| with g1=(u_p,u_q), g2=(v_p,v_q).
Route 2 (brute force, used as the check for small pairs): count distinct (chi_p(x), chi_q(x)) over the lcm-torus.
Prints the transversal pairs and the forced overlap for the pool; verifies (5,7) explicitly both ways + by the
2x2 kernel determinant."""
import json, sys
from math import gcd, lcm
pool=json.load(open(sys.argv[1]))["pool"]
P={r["p"]:r for r in pool}
def image_size(a,b):
    ea,eb=a["e"],b["e"]
    g1=(a["u"]%ea,a["u"]%eb if False else b["u"]%eb); g2=(a["v"]%ea,b["v"]%eb)
    # subgroup generated by g1 in Z/ea x Z/eb
    def mults(g):
        s=set(); x=(0,0)
        while True:
            s.add(x); x=((x[0]+g[0])%ea,(x[1]+g[1])%eb)
            if x==(0,0): return s
    H1=mults(g1); H2=mults(g2)
    return len(H1)*len(H2)//len(H1&H2)
def image_size_bf(a,b):
    ea,eb=a["e"],b["e"]; T=lcm(ea,eb); s=set()
    for k in range(T):
        for l in range(T):
            s.add(((a["u"]*k+a["v"]*l)%ea,(b["u"]*k+b["v"]*l)%eb))
    return len(s)
ps=sorted(P)
trans=[]; total_forced=0.0
rows=[]
for i,p in enumerate(ps):
    for q in ps[i+1:]:
        a,b=P[p],P[q]; im=image_size(a,b); idx_sum=a["e"]*b["e"]//im
        rows.append((p,q,a["e"],b["e"],im,idx_sum))
        if idx_sum==1: trans.append((p,q,1/im))
print("pairs:",len(rows),"transversal (L_p+L_q=Z^2):",len(trans))
print("transversal pairs sorted by forced overlap 1/e_pq:")
for p,q,ov in sorted(trans,key=lambda t:-t[2])[:15]: print(f"  ({p},{q}) e_pq={P[p]['e']*P[q]['e']} forced overlap {ov:.5f}")
# explicit checks for (5,7)
a,b=P[5],P[7]
print("(5,7): image size route1 =",image_size(a,b),"brute force =",image_size_bf(a,b),"e5*e7 =",a["e"]*b["e"])
# kernel determinant: solve u5 k + v5 l ≡ 0 (4), u7 k + v7 l ≡ 0 (6) -> enumerate kernel on [0,12)^2 and count
T=lcm(a["e"],b["e"]); ker=[(k,l) for k in range(T) for l in range(T) if (a["u"]*k+a["v"]*l)%a["e"]==0 and (b["u"]*k+b["v"]*l)%b["e"]==0]
print("(5,7): kernel points in [0,%d)^2 = %d -> index %d"%(T,len(ker),T*T//len(ker)))
# every pair of cosets meets:
ok=all(any((a["u"]*k+a["v"]*l)%a["e"]==c5 and (b["u"]*k+b["v"]*l)%b["e"]==c7 for k in range(T) for l in range(T)) for c5 in range(a["e"]) for c7 in range(b["e"]))
print("(5,7): every (c5,c7) realised by some point:",ok)
# non-transversal pairs summary
nt=[r for r in rows if r[5]>1]
from collections import Counter
print("index of L_p+L_q over non-transversal pairs:",sorted(Counter(r[5] for r in nt).items()))
json.dump({"rows":rows},open("pairs_%s.json"%sys.argv[1].split('_')[1].split('.')[0],"w"))
