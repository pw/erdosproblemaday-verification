#!/usr/bin/env python3
"""Soundness control for add_perm_sb + class SB together (brute force, tiny instances with a high-side symmetry).
Orbit coverage under the group generated by class transpositions AND the high permutations: every base solution
must have an image accepted by the SB CNF.  Mutation: reverse one comparison in a perm chain -> must lose orbits
or accept non-leaders (reported)."""
import itertools, sys
from pysat.solvers import Cadical153
sys.path.insert(0, '.')
import fsenc, c4cnf

def group_closure(gens, n):
    G = {tuple(range(n))}; frontier = [tuple(range(n))]
    while frontier:
        g = frontier.pop(); 
        for s in gens:
            c = tuple(s[g[i]] for i in range(n))
            if c not in G: G.add(c); frontier.append(c)
    return G

def run(h, blocks, target_deg, sigmas, mutate=False):
    n = h + len(blocks)
    S = list(range(h)); fixed = [(x, h + i) for i, b in enumerate(blocks) for x in b]
    target = {v: target_deg for v in range(h, n)}
    cnf, var, F, adjS, st, cls = fsenc.build(n, S, fixed, target, highs=(), sb="all", r1=False, r1b=False)
    perms = [fsenc.high_perm(h, h, blocks, s) for s in sigmas]
    top = max([abs(l) for c in cnf.clauses for l in c] + [len(var)])
    nb = len(cnf.clauses)
    top, nc = fsenc.add_perm_sb(cnf, var, n, perms, top)
    if mutate:
        c = list(cnf.clauses[nb]); c[-2], c[-1] = -c[-2], -c[-1]; cnf.clauses[nb] = c
    base, _, _, _ = c4cnf.build(n, S, fixed, target)
    gens = [tuple(p) for p in perms]
    for C in cls:
        for i, j in zip(C, C[1:]):
            t = list(range(n)); t[i], t[j] = j, i; gens.append(tuple(t))
    G = group_closure(gens, n)
    edges = sorted(var)
    sols = []
    with Cadical153(bootstrap_with=base.clauses) as bs:
        while bs.solve():
            m = set(l for l in bs.get_model() if l > 0)
            sols.append(frozenset(e for e in edges if var[e] in m))
            bs.add_clause([-var[e] if var[e] in m else var[e] for e in edges])
    solset = set(sols)
    acc = 0; lost = 0; nonleader_acc = 0
    with Cadical153(bootstrap_with=cnf.clauses) as s2:
        def accepted(g):
            return s2.solve(assumptions=[var[e] if e in g else -var[e] for e in edges])
        seen = set()
        for g in sols:
            if g in seen: continue
            orbit = set()
            for p in G:
                orbit.add(frozenset(tuple(sorted((p[a], p[b]))) for a, b in g))
            assert orbit <= solset
            seen |= orbit
            vec = lambda gg: [1 if e in gg else 0 for e in edges]
            leader = min(orbit, key=vec)
            if not any(accepted(o) for o in orbit): lost += 1
            if not accepted(leader): nonleader_acc += 1
    return dict(n=n, group=len(G), classes=[len(c) for c in cls], perm_clauses=nc, solutions=len(sols),
                orbits=len({min(vec2 for vec2 in [tuple(sorted(o)) for o in [g]]) for g in sols}) if False else None,
                lost_orbits=lost, leader_rejected=nonleader_acc)

# 3 highs, 'triangle' of pair-blocks + singles + empties: Aut = S3 on highs
B1 = [(0, 1), (0, 2), (1, 2), (0,), (1,), (2,), (), ()]
print("S3 pairs   ", run(3, B1, 2, [[1, 0, 2], [0, 2, 1]]))
print("S3 pairs d3", run(3, B1, 3, [[1, 0, 2], [0, 2, 1]]))
B2 = [(0, 1), (0,), (0,), (1,), (1,), (), ()]
print("S2 swap d2 ", run(2, B2, 2, [[1, 0]]))
print("S2 swap d3 ", run(2, B2, 3, [[1, 0]]))
print("MUTATED    ", run(3, B1, 3, [[1, 0, 2], [0, 2, 1]], mutate=True))
