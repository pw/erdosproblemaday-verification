"""Referee's third check of a tree manifest, by a different route from replay.py:
 - residual of each node from the closed formula R = R0 ∩ ⋂_{f∈F} Nbar(f) \ ⋃(excluded orbits on the root path)
 - the group generated by transpositions = Young subgroup of the connected components of the transposition graph
   on [n]; orbit of r = all 5-sets with the same block-intersection signature (combinatorial, no closure);
 - R preserved  <=>  R is a union of signature classes;
 - leaves.txt residuals equal the formula residuals; every childless node is a leaf; ids unique.
"""
import sys, json
from itertools import combinations
out = sys.argv[1]
man = json.load(open(out + '/manifest.json'))
n, s, v, u = man['n'], man['s'], man['v'], man['u']
V = list(combinations(range(n), 5)); S = [set(x) for x in V]
assert S[v] == {0,1,2,3,4} and S[u] == {0,1,2,3,5}
N = len(V)
ok_pair = lambda a, b: len(S[a] & S[b]) != 3      # Gbar adjacency for a != b
R0 = {w for w in range(N) if w not in (v, u) and ok_pair(w, v) and ok_pair(w, u)}
ids = [nd['id'] for nd in man['nodes']]; assert len(ids) == len(set(ids))
nodes = {nd['id']: nd for nd in man['nodes']}
kids = {}
for nd in man['nodes']:
    if nd['parent'] is not None:
        assert nd['parent'] in nodes; kids.setdefault(nd['parent'], []).append(nd['id'])
roots = [i for i in nodes if nodes[i]['parent'] is None]; assert roots == [1]
def path(i):
    p = []
    while i is not None: p.append(i); i = nodes[i]['parent']
    return p[::-1]
def components(gens):
    par = list(range(n))
    def f(x):
        while par[x] != x: x = par[x]
        return x
    for a, b in gens: par[f(a)] = f(b)
    comp = {}
    for x in range(n): comp.setdefault(f(x), []).append(x)
    return list(comp.values())
def sig(w, blocks): return tuple(len(S[w] & set(B)) for B in blocks)
Rcache = {}
def resid(i):
    if i in Rcache: return Rcache[i]
    nd = nodes[i]; R = set(R0)
    for f in nd['F']:
        R = {w for w in R if w != f and ok_pair(w, f)}
    for a in path(i)[1:]:
        if nodes[a]['kind'] == 'exclude': R -= set(nodes[a]['excluded_orbit'])
    Rcache[i] = R; return R
nint = 0
for i in sorted(nodes):
    nd = nodes[i]; R = resid(i)
    assert len(R) == nd['size'], i
    assert nd['tau'] == s - 1 - len(nd['F'])
    ch = kids.get(i, [])
    if not ch: assert 'leaf' in nd; continue
    nint += 1
    assert len(ch) == 2
    blocks = components(nd['gens'])
    r = nd['r']; assert r in R
    cls = {}
    for w in range(N): cls.setdefault(sig(w, blocks), set()).add(w)
    for c in cls.values():
        assert c <= R or not (c & R), f'R not a union of signature classes at node {i}'
    orb = cls[sig(r, blocks)]
    ex = [nodes[c] for c in ch if nodes[c]['kind'] == 'exclude']; inc = [nodes[c] for c in ch if nodes[c]['kind'] == 'include']
    assert len(ex) == 1 and len(inc) == 1
    assert set(ex[0]['excluded_orbit']) == orb, f'orbit mismatch at {i}'
    assert inc[0]['F'] == nd['F'] + [r] and ex[0]['F'] == nd['F']
lines = open(out + '/leaves.txt').read().splitlines()
seen = set()
for l in lines:
    t = list(map(int, l.split())); lid, tau, k = t[:3]; vs = [x - 1 for x in t[3:]]
    assert lid not in seen; seen.add(lid)
    assert k == len(vs) == len(set(vs)) and set(vs) == resid(lid) and tau == nodes[lid]['tau'] and lid not in kids
for i in nodes:
    if i not in kids and i not in seen:
        assert len(resid(i)) < nodes[i]['tau'], f'leaf {i} neither solved nor size-pruned'
print(f'CHECK3 OK nodes={len(nodes)} internal={nint} leaves_in_file={len(seen)} childless={sum(1 for i in nodes if i not in kids)}')
