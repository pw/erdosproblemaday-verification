"""For primes p > 13 the permutation module F_p^1287 of Sym(13) on 5-sets is semisimple, multiplicity-free with six irreducible
constituents (the Johnson-scheme eigenspaces), so the submodule generated by v = 1_W is everything iff E_i v != 0 mod p for all i,
which holds if v^T E_i v != 0 mod p. Compute q_i = v^T E_i v exactly; list primes > 13 dividing a numerator (to be checked directly)."""
from fractions import Fraction
from itertools import combinations
from wstruct import WA
V = [frozenset(c) for c in combinations(range(13), 5)]
# inner distribution of W: a_j = #ordered pairs (S,S') in W with |S n S'| = 5 - j
a = [0] * 6
for S in WA:
    for T in WA: a[5 - len(S & T)] += 1
print('inner distribution a_j (j = 0..5):', a, 'sum', sum(a))
# eigenvalues of the distance-j relation A_j of J(13,5) on eigenspace i:  P_j(i) (Eberlein), computed from the definition
from math import comb
def P(j, i, n=13, k=5):
    return sum((-1) ** t * comb(i, t) * comb(k - i, j - t) * comb(n - k - i, j - t) for t in range(j + 1))
m = [comb(13, i) - comb(13, i - 1) if i else 1 for i in range(6)]          # multiplicities
val = [comb(5, j) * comb(8, j) for j in range(6)]                           # valencies
assert sum(m) == 1287 and all(sum(m[i] * P(j, i) for i in range(6)) == (1287 if j == 0 else 0) for j in range(6))
# v^T E_i v = (m_i / |V|) * sum_j a_j P_j(i) / val_j
q = [Fraction(m[i], 1287) * sum(Fraction(a[j] * P(j, i), val[j]) for j in range(6)) for i in range(6)]
print('q_i = v^T E_i v:', [str(x) for x in q], 'sum', sum(q))
def pf(n):
    n = abs(n); out = set(); d = 2
    while d * d <= n:
        while n % d == 0: out.add(d); n //= d
        d += 1
    if n > 1: out.add(n)
    return out
bad = set()
for x in q: bad |= {p for p in pf(x.numerator) | pf(x.denominator) if p > 13}
print('primes > 13 dividing a numerator or denominator of some q_i (need a direct rank check):', sorted(bad))
